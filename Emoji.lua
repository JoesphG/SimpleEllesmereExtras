-- name -> hex for every lookup; char -> hex split by whether the character
-- converts on its own or only with VS16.
local byName, byBare, byAny = {}, {}, {}
local charOf = {}

for _, e in ipairs(EMOJI) do
    local hex, char, name = e[1], e[2], e[3]
    byName[name] = hex
    byAny[char] = hex
    charOf[hex] = char
    -- Four UTF-8 bytes means U+10000 and up: emoji by default.
    if #char == 4 then
        byBare[char] = hex
    end
end

for alias, hex in pairs(ALIASES) do
    byName[alias] = hex
    local char = charOf[hex]
    if char then
        byBare[char] = hex
    end
end

-- Looked up as a whole word rather than matched as a pattern, so there is
-- nothing to escape: ":)" is a table key, not a stray capture close.
local asciiWord = {}
for _, a in ipairs(ASCII) do
    local hex = byName[a[2]]
    if hex then
        asciiWord[a[1]] = hex
    end
end

local function Enabled()
    return ns.DB().emoji ~= false
end

-- Derived from the chat font, not fixed at DEFAULT_SIZE. An inline texture
-- taller than the line box overlaps the line above it, and chat line height
-- comes from the font, which the user sets. A ScrollingMessageFrame is a
-- FontInstance, so the frame can be asked directly. Blizzard's frame is the
-- one asked even when EllesmereUIChat is drawing, since it is fed from the
-- same pipeline; `/euiemoji size N` overrides either way.
local function Size()
    local size = ns.DB().emojiSize
    if type(size) == "number" and size >= 8 and size <= 32 then
        return size
    end

    local frame = DEFAULT_CHAT_FRAME
    if frame and frame.GetFont then
        local _, points = frame:GetFont()
        if not (issecretvalue and issecretvalue(points)) and type(points) == "number" then
            if points >= 8 and points <= 32 then
                return math.floor(points)
            end
        end
    end

    return DEFAULT_SIZE
end

-- Width stated as well as height: the art is square, and leaving width to the
-- default lets a file that is not stretch the line it sits in.
local function Tag(hex)
    local size = Size()
    return ("|T%s%s.png:%d:%d|t"):format(ART, hex, size, size)
end

-- VS16, the emoji presentation selector.
local VS16 = "\239\184\143"

-- The zero-width joiner, and the five skin-tone modifiers. Both only ever
-- appear as part of a sequence we have no single bitmap for.
local ZWJ = "\226\128\141"
local SKIN = "\240\159\143[\187-\191]"

-- Any multi-byte UTF-8 run. Continuation bytes never start a character, so this
-- brackets exactly one codepoint at a time.
local UTF8 = "[\194-\244][\128-\191]+"

local function Substitute(text)
    if text == "" then
        return text
    end

    -- A joined or skin-toned sequence has no bitmap of its own, so its parts
    -- convert individually. Drop the joiners and modifiers instead of leaving
    -- them between the pieces, where the font draws them as empty boxes.
    text = text:gsub(ZWJ, ""):gsub(SKIN, "")

    -- VS16 present: the sender asked for emoji presentation, so convert
    -- whatever it is attached to.
    text = text:gsub("(" .. UTF8 .. ")" .. VS16, function(char)
        local hex = byAny[char]
        return hex and Tag(hex) or nil
    end)

    text = text:gsub(UTF8, function(char)
        local hex = byBare[char]
        return hex and Tag(hex) or char
    end)

    text = text:gsub(":([%w_]+):", function(n)
        local hex = byName[n:lower()]
        return hex and Tag(hex) or nil
    end)

    -- WHOLE WORDS ONLY.
    --
    -- An ASCII smiley is two or three characters of punctuation, which turns up
    -- inside plenty of things that are not smileys: ":/" lives in every URL
    -- ("https://..."), ":P" in every crafter GUID ("::Player-3725-0C553989").
    -- Substituting those corrupts whatever they were part of -- a mangled URL,
    -- or an item link that renders as raw escape text.
    --
    -- So a smiley converts only when it stands alone as a word. That also means
    -- a mis-read escape sequence upstream cannot do any damage on its own: the
    -- body of a link is one long unbroken run, and no part of it is ever a
    -- word. Same rule ElvUI uses, and the reason it does not have this bug.
    text = text:gsub("%S+", function(word)
        local hex = asciiWord[word]
        return hex and Tag(hex) or nil
    end)

    return text
end

-- Only plain text is rewritten. WoW escape sequences are copied verbatim: an
-- emoji dropped inside |Hitem:...|h[Name]|h breaks the link, and one inside a
-- |T...|t or a |cAARRGGBB mangles it. A ":)" in an item name stays a ":)".
local function Rewrite(msg)
    local out, i = {}, 1

    while true do
        local s = msg:find("|", i, true)
        if not s then
            out[#out + 1] = Substitute(msg:sub(i))
            break
        end

        out[#out + 1] = Substitute(msg:sub(i, s - 1))

        local kind = msg:sub(s + 1, s + 1)
        local e
        if kind == "H" then
            -- |Hlink|htext|h -- the display text belongs to the link.
            local _, close = msg:find("|h.-|h", s)
            e = close or s + 1
        elseif kind == "T" then
            local _, close = msg:find("|t", s, true)
            e = close or s + 1
        elseif kind == "A" then
            local _, close = msg:find("|a", s, true)
            e = close or s + 1
        elseif kind == "K" then
            -- Secret-value placeholder (12.x). EllesmereUIChat strips these
            -- wholesale; either way the payload is not text to rewrite.
            local _, close = msg:find("|k", s, true)
            e = close or s + 1
        elseif kind == "c" then
            -- Two colour forms, and only one is fixed width. |cAARRGGBB is ten
            -- characters; |cn<NAME>: is not -- and modern item links use it for
            -- the quality colour. Taking ten off a named colour swallows the
            -- |H that follows, so the rest of the link arrives here as ordinary
            -- text: the ":P" in a crafter GUID ("::Player-3725-...") became an
            -- emoji, and the link died.
            -- Same split EllesmereUIChat_Engine.lua makes at its own escape
            -- walker; keep the two in step.
            if msg:sub(s + 2, s + 2) == "n" then
                local colon = msg:find(":", s + 3, true)
                e = colon or (s + 2)
            else
                e = s + 9 -- |cAARRGGBB
            end
        else
            e = s + 1 -- |r, |n, ||, and anything we do not know
        end

        out[#out + 1] = msg:sub(s, e)
        i = e + 1
    end

    return table.concat(out)
end

