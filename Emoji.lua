--  Emoji.lua
--
--  LOCAL PATCH -- not upstream. Tracked in AddOns/.git; see
--  .addon-patches/README.md. Own code, written against the Blizzard API; the
--  behaviour is modelled on ElvUI's chat emoji but none of its code is used
--  here -- same stance as HyperlinkHover.lua.
--
--  Renders emoji in chat two ways:
--
--    * a real Unicode emoji, typed with the OS picker or sent by another
--      player. WoW's fonts have no glyphs for these, so untouched they arrive
--      as empty boxes -- that is the case this file exists for.
--    * a `:name:` shortcode, or a classic ASCII smiley like :) or </3.
--
--  Both become an inline |T...|t texture. Every single-codepoint emoji Noto
--  Color Emoji has art for is covered, around 1400 of them; the shortcode is
--  the character's Unicode name, slugified, and ALIASES below adds the short
--  ones worth typing. `/euiemoji list <text>` searches.
--
--  ZWJ and skin-tone sequences are not covered: those are GSUB ligatures in the
--  font rather than codepoints, so there is no single bitmap to point at. They
--  pass through untouched.
--
--  WHICH BARE CHARACTERS CONVERT
--
--  Not all of them, deliberately. The set includes (c), (R), (TM), the arrows
--  and the dingbats, which people type as text and do not want turned into
--  pictures. So: an astral codepoint (4 UTF-8 bytes, U+10000 and up) is emoji
--  by default and always converts; anything in the BMP converts only if the
--  sender appended VS16 to ask for emoji presentation, or if we gave it an
--  alias below -- an alias is us deciding it is worth converting bare.
--
--  WHAT IS NOT DONE, DELIBERATELY: the text you SEND is left alone. Typing
--  `:smile:` puts `:smile:` on the wire, so players without this patch read
--  something sensible instead of nothing.
--
--  Off with `/euiemoji`; the setting is account-wide and defaults on.
-------------------------------------------------------------------------------
