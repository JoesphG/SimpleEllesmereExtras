-- A message event filter, not a hook on our own render layer: EllesmereUIChat
-- draws its own text but is fed from Blizzard's message pipeline, so rewriting
-- here reaches our frames and Blizzard's alike.
local function Filter(_, _, msg, ...)
    if not Enabled() or not msg or msg == "" then
        return false
    end
    if issecretvalue and issecretvalue(msg) then
        return false
    end
    return false, Rewrite(msg), ...
end

if ChatFrame_AddMessageEventFilter then
    for _, event in ipairs(EVENTS) do
        ChatFrame_AddMessageEventFilter(event, Filter)
    end
end

local MAX_LISTED = 40

_G.SLASH_EUIEMOJI1 = "/euiemoji"
_G.SlashCmdList.EUIEMOJI = function(input)
    local arg, value = (input or ""):lower():match("^%s*(%S*)%s*(.-)%s*$")

    if arg == "size" then
        local n = tonumber(value)
        if not n or n < 8 or n > 32 then
            print("SimpleEllesmereExtras emoji: size takes 8-32.")
            return
        end
        ns.DB().emojiSize = n
        print(("SimpleEllesmereExtras emoji: size %d. %s"):format(n, Tag(byName.thumbsup)))
        return
    end

    if arg == "list" then
        -- The set is far too large to dump, so a search term is required.
        if value == "" then
            print("SimpleEllesmereExtras emoji: /euiemoji list <text> -- there are too many to list.")
            return
        end

        local hits = {}
        for name, hex in pairs(byName) do
            if name:find(value, 1, true) then
                hits[#hits + 1] = Tag(hex) .. " :" .. name .. ":"
            end
        end
        table.sort(hits)

        if #hits == 0 then
            print("SimpleEllesmereExtras emoji: nothing matching " .. value .. ".")
            return
        end

        local shown = math.min(#hits, MAX_LISTED)
        for i = 1, shown, 5 do
            print(table.concat(hits, "  ", i, math.min(i + 4, shown)))
        end
        if #hits > shown then
            print(("SimpleEllesmereExtras emoji: %d more, narrow the search."):format(#hits - shown))
        end
        return
    end

    if arg ~= "" then
        print("SimpleEllesmereExtras emoji: /euiemoji toggles, /euiemoji size N, /euiemoji list <text>.")
        return
    end

    ns.DB().emoji = not Enabled()
    print("SimpleEllesmereExtras emoji: " .. (Enabled() and "on" or "off") .. ".")
end
