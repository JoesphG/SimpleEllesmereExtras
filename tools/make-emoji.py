#!/usr/bin/env python3
"""Build the chat emoji art for Emoji.lua.

Art comes from Noto Color Emoji, whose CBDT table stores one PNG per glyph, so
the bitmaps are lifted out as-is rather than rendered. Run from the addon folder:

    python3 .addon-patches/tools/make-emoji.py

Covers every single-codepoint emoji the font has art for -- around 1400. ZWJ and
skin-tone sequences are out of scope: they are ligatures in GSUB, not codepoints.

Writes Media/emoji/<codepoint hex>.png and rewrites the EMOJI
table in the Lua file between its GENERATED markers. Shortcodes are the
character's Unicode name, slugified; the short aliases worth typing are
hand-written in the Lua file, and this tool fails if one of them names a
codepoint it did not emit.

Noto Color Emoji is SIL Open Font License 1.1 -- redistribution is fine, and the
licence is copied next to the art.
"""

import os
import re
import struct
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import png  # noqa: E402

FONT = "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"
ART = "Media/emoji"
LUA = "Emoji.lua"

BEGIN = "    -- GENERATED by tools/make-emoji.py -- do not edit by hand.\n"
END = "    -- END GENERATED\n"

# Codepoints the font carries that are not emoji to substitute on their own.
SKIP = {
    0x200D,  # zero width joiner
    0xFE0E,  # text presentation selector
    0xFE0F,  # emoji presentation selector
    0x20E0,  # combining enclosing circle backslash
    0x20E3,  # combining enclosing keycap
}


def wanted(cp):
    if cp < 0xA9 or cp in SKIP:
        return False
    if 0x1F3FB <= cp <= 0x1F3FF:  # skin tone modifiers
        return False
    if 0x1F1E6 <= cp <= 0x1F1FF:  # regional indicators: half a flag each
        return False
    if 0xE0020 <= cp <= 0xE007F:  # tag characters
        return False
    if 0xE000 <= cp <= 0xF8FF or cp >= 0xF0000:  # private use, incl. Noto's own
        return False
    return True


def slug(cp):
    name = unicodedata.name(chr(cp), "")
    if not name:
        return None
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return s or None


class Noto:
    def __init__(self, path):
        self.d = d = open(path, "rb").read()
        (numTables,) = struct.unpack(">H", d[4:6])
        self.tables = {}
        for i in range(numTables):
            o = 12 + i * 16
            tag, _, off, ln = struct.unpack(">4sIII", d[o : o + 16])
            self.tables[tag.decode("latin1")] = (off, ln)
        self.cmap = self._cmap()
        self.bitmaps = self._bitmaps()

    def _cmap(self):
        d = self.d
        base = self.tables["cmap"][0]
        (n,) = struct.unpack(">H", d[base + 2 : base + 4])
        sub = None
        for i in range(n):
            _, _, off = struct.unpack(">HHI", d[base + 4 + i * 8 : base + 12 + i * 8])
            (fmt,) = struct.unpack(">H", d[base + off : base + off + 2])
            if fmt == 12:
                sub = base + off
                break
        assert sub, "no format 12 cmap"
        m = {}
        (ngroups,) = struct.unpack(">I", d[sub + 12 : sub + 16])
        for g in range(ngroups):
            o = sub + 16 + g * 12
            s, e, gid = struct.unpack(">III", d[o : o + 12])
            for c in range(s, e + 1):
                m[c] = gid + (c - s)
        return m

    def _bitmaps(self):
        d = self.d
        cblc = self.tables["CBLC"][0]
        cbdt = self.tables["CBDT"][0]
        (numSizes,) = struct.unpack(">I", d[cblc + 4 : cblc + 8])
        out = {}
        for s in range(numSizes):
            rec = cblc + 8 + s * 48
            idxArrayOff, _, numIdxSubTables = struct.unpack(">III", d[rec : rec + 12])
            for t in range(numIdxSubTables):
                o = cblc + idxArrayOff + t * 8
                first, last, addOff = struct.unpack(">HHI", d[o : o + 8])
                st = cblc + idxArrayOff + addOff
                fmt, imgFmt, imgDataOff = struct.unpack(">HHI", d[st : st + 8])
                if fmt == 1:
                    count = last - first + 2
                    offs = struct.unpack(">%dI" % count, d[st + 8 : st + 8 + 4 * count])
                    for i, gid in enumerate(range(first, last + 1)):
                        a, b = offs[i], offs[i + 1]
                        if b > a:
                            out[gid] = (cbdt + imgDataOff + a, imgFmt)
                elif fmt == 2:
                    (imageSize,) = struct.unpack(">I", d[st + 8 : st + 12])
                    for i, gid in enumerate(range(first, last + 1)):
                        out[gid] = (cbdt + imgDataOff + i * imageSize, imgFmt)
        return out

    def png(self, cp):
        gid = self.cmap.get(cp)
        if gid is None or gid not in self.bitmaps:
            return None
        off, imgFmt = self.bitmaps[gid]
        d = self.d
        # imageFormat 17/18/19: metrics, then a uint32 length, then the PNG.
        head = {17: 5, 18: 8, 19: 0}[imgFmt]
        (ln,) = struct.unpack(">I", d[off + head : off + head + 4])
        return d[off + head + 4 : off + head + 4 + ln]


def lua_bytes(cp):
    return "".join("\\%d" % b for b in chr(cp).encode("utf-8"))


def lua_aliases(src):
    """The hand-written ALIASES table, so a dead alias fails the build."""
    block = src.split("local ALIASES = {", 1)[1].split("}", 1)[0]
    return dict(re.findall(r'(\w+)\s*=\s*"([0-9a-f]+)"', block))


def main():
    if not os.path.isfile(LUA):
        sys.exit("run me from the SimpleEllesmereExtras folder")
    if not os.path.exists(FONT):
        sys.exit("need %s (apt install fonts-noto-color-emoji)" % FONT)

    noto = Noto(FONT)
    src = open(LUA, "rb").read().decode("utf-8")
    aliases = lua_aliases(src)

    os.makedirs(ART, exist_ok=True)
    for stale in os.listdir(ART):
        if stale.endswith(".png"):
            os.remove(os.path.join(ART, stale))

    rows, slugs, unnamed = [], {}, []
    for cp in sorted(noto.cmap):
        if not wanted(cp):
            continue
        blob = noto.png(cp)
        if not blob:
            continue
        name = slug(cp)
        if not name:
            unnamed.append(cp)
            continue
        if name in slugs:
            sys.exit("slug collision: %s is both U+%04X and U+%04X" % (name, slugs[name], cp))
        slugs[name] = cp

        w, h, rgba = png.read_rgba(blob)
        side, sq = png.square(w, h, rgba)
        w2, h2, small = png.halve(side, side, sq)
        with open(os.path.join(ART, "%04x.png" % cp), "wb") as fh:
            fh.write(png.write_rgba(w2, h2, small))

        rows.append('    { "%04x", "%s", "%s" },\n' % (cp, lua_bytes(cp), name))

    emitted = {("%04x" % cp) for cp in slugs.values()}
    dead = sorted(a for a, hexcp in aliases.items() if hexcp not in emitted)
    if dead:
        sys.exit("aliases naming a codepoint with no art: " + ", ".join(dead))

    a = src.index(BEGIN) + len(BEGIN)
    b = src.index(END)
    open(LUA, "wb").write((src[:a] + "".join(rows) + src[b:]).encode("utf-8"))

    total = sum(os.path.getsize(os.path.join(ART, f)) for f in os.listdir(ART) if f.endswith(".png"))
    print("%d emoji, %d aliases, %.2f MB of art" % (len(rows), len(aliases), total / 1e6))
    if unnamed:
        print("skipped %d with no Unicode name in this Python: %s"
              % (len(unnamed), " ".join("U+%04X" % c for c in unnamed)))


if __name__ == "__main__":
    main()
